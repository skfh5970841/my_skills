SENT = re.compile(r"[^.!?]*[.!?]+|[^.!?]+$")
results = {}
for name, text in TESTS.items():
    sents = [s.strip() for s in SENT.findall(text) if len(re.sub(r"[\s.!?]", "", s)) >= 2]
    results[name] = measure(name, sents)

(OUT / "test_outputs_metrics_v2.json").write_text(
    json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")

for name, m in results.items():
    tr = m["transitions"]
    top = [(t, v["count"]) for t, v in list(tr.items())[:8] if v["count"]]
    print(f"\n[{name}] 문장수={m['sentences']} 평균={m['sent_len_chars']['mean']}자 "
          f"질문%={m['question_ratio_pct']}")
    print("  전환어:", ", ".join(f"{t}×{c}" for t, c in top) or "(없음)")
    print("  우리:", round(m['reader_terms_per10k']['우리'],1),
          "/ 당신:", round(m['reader_terms_per10k']['당신'],1))
